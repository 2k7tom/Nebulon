package com.nebulon.config;

/** "Inferno Demonlord" (Combat): helpers for the Blaze slayer boss. */
public class InfernoDemonlordSettings {
	public boolean enabled = false;
	/** "Hide Fire Particles and Fireballs": while the boss is spawned, no flame / lava particles and no fireballs. */
	public boolean hideFire = true;
	/** "Hide Potion Particles": while the boss is spawned, no potion / effect swirl particles. */
	public boolean hidePotionParticles = true;
	/** "Attunement Highlight": the boss and its demons glow in the colour of their current attunement. */
	public boolean attunementHighlight = true;
	/** "Fire Pillar Alert": a title on screen when a fire pillar spawns. */
	public boolean firePillarAlert = true;
}
